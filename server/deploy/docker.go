// Docker is the Compose target: a hardened compose file generated from authfly.yaml into .authfly/compose.yml.
type Docker struct{ C *Config }

func (d Docker) project() string { return "authfly-" + d.C.Name }
func (d Docker) composeFile() string {
	return filepath.Join(d.C.State(), "compose.yml")
}
func (d Docker) compose(args ...string) (string, error) {
	return run("docker", append([]string{"compose", "-p", d.project(), "-f", d.composeFile()}, args...)...)
}

// verifyImage makes sure ref@digest is present locally and matches the channel (image ID for local builds, repo
// digest for registry images). Returns the reference to put in compose.
func verifyImage(spec string) (string, error) {
	ref, digest, ok := strings.Cut(spec, "@")
	if !ok || !strings.HasPrefix(digest, "sha256:") {
		return "", fmt.Errorf("image %q is not pinned by sha256 digest", spec)
	}
	check := func() bool {
		out, err := run("docker", "image", "inspect", "-f", "{{.Id}} {{join .RepoDigests \" \"}}", ref)
		if err != nil {
			return false
		}
		f := strings.Fields(out)
		if len(f) > 0 && f[0] == digest {
			return true
		}
		for _, rd := range f[1:] {
			if strings.HasSuffix(rd, "@"+digest) {
				return true
			}
		}
		return false
	}
	if check() {
		return ref, nil
	}
	repo := ref
	if i := strings.LastIndex(ref, ":"); i > strings.LastIndex(ref, "/") {
		repo = ref[:i]
	}
	if _, err := run("docker", "pull", "-q", repo+"@"+digest); err != nil { // pull by digest: the registry cannot substitute content
		return "", fmt.Errorf("image %s: not present with digest %s and pull failed: %w", ref, digest, err)
	}
	if _, err := run("docker", "tag", repo+"@"+digest, ref); err != nil {
		return "", err
	}
	if !check() {
		return "", fmt.Errorf("image %s: digest mismatch after pull", ref)
	}
	return ref, nil
}

func yq(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }

func envBlock(e map[string]string, indent string) string {
	var b strings.Builder
	for _, k := range sortedKeys(e) {
		fmt.Fprintf(&b, "%s%s: %s\n", indent, k, yq(e[k]))
	}
	return b.String()
}

const hardening = `    restart: unless-stopped
    read_only: true
    cap_drop: [ALL]
    security_opt: ["no-new-privileges:true"]
    tmpfs: ["/tmp:size=16m,mode=1777"]
    pids_limit: 256
    logging: { driver: local, options: { max-size: "10m", max-file: "3" } }
`

// Render writes compose.yml for a release.
func (d Docker) Render(rel *Release, p Pack) error {
	c := d.C
	imgs := map[string]string{}
	for _, n := range []string{"authfly", "console", "stalwart"} {
		spec, ok := rel.Images[n]
		if !ok {
			return fmt.Errorf("release %s has no %s image", rel.Version, n)
		}
		ref, err := verifyImage(spec)
		if err != nil {
			return err
		}
		if n == "stalwart" {
			ref = spec // immutable reference in compose
		}
		imgs[n] = ref
	}
	const sd = "/run/secrets"
	ae := c.authflyEnv(p, "http://stalwart:8080", "stalwart:25", sd, "/data")
	ae["AUTHFLY_LEGAL_DIR"] = "/legal"
	httpPorts := fmt.Sprintf("      - \"%d:4000\"\n", c.HTTP.Port)
	if c.HTTP.TLS != "off" {
		httpPorts = fmt.Sprintf("      - \"%d:4443\"\n", c.HTTP.Port)
		if c.HTTP.HTTPPort != 0 {
			httpPorts += fmt.Sprintf("      - \"%d:4080\"\n", c.HTTP.HTTPPort)
		}
	}
	sec := func(names ...string) string {
		return "    secrets: [" + strings.Join(names, ", ") + "]\n"
	}
	var b strings.Builder
	fmt.Fprintf(&b, `# GENERATED by authfly from %s (release %s). Do not edit: change authfly.yaml and run `+"`authfly deploy`"+`.
# Public: Authfly HTTP(S) and the mail ports. Localhost only: Stalwart management (%d) and the Console (%d), reach them
# with ssh -L. Secrets: files in .authfly/run (0600, owned by the container user), mounted under /run/secrets.
name: %s
services:
  stalwart:
    image: %s
    env_file: [run/stalwart.env]   # Stalwart reads the recovery admin from the environment only (no *_FILE support)
    sysctls: { net.ipv4.ip_unprivileged_port_start: 0 }  # bind 25/465/993 as the unprivileged stalwart user, no capabilities
    volumes:
      - ./stalwart/config.json:/etc/stalwart/config.json:ro
      - stalwart-data:/var/lib/stalwart
    ports:
      - "127.0.0.1:%d:8080"
      - "%d:25"
      - "%d:465"
      - "%d:993"
    mem_limit: 1g
%s    networks: [edge]
  stalwart-init:
    image: %s
    command: ["init-stalwart"]
    depends_on: [stalwart]
    restart: "no"
    read_only: true
    cap_drop: [ALL]
    security_opt: ["no-new-privileges:true"]
    environment:
%s%s    networks: [edge]
  authfly:
    image: %s
    depends_on: { stalwart-init: { condition: service_completed_successfully } }
    environment:
%s%s    volumes:
      - authfly-data:/data
      - ./legal:/legal:ro
    ports:
%s    mem_limit: 256m
%s    networks: [edge]
  console:
    image: %s
    depends_on: { stalwart-init: { condition: service_completed_successfully }, authfly: { condition: service_started } }
    environment:
%s%s    volumes: [console-data:/data]
    ports:
      - "127.0.0.1:%d:4500"
    mem_limit: 128m
%s    networks: [edge]
networks:
  edge: {}
volumes:
  stalwart-data:
  authfly-data:
  console-data:
secrets:
`, c.Path(), rel.Version, c.Ports.Management, c.Ports.Console, d.project(),
		imgs["stalwart"], c.Ports.Management, c.Mail.Ports.SMTP, c.Mail.Ports.Submissions, c.Mail.Ports.IMAPS, hardening,
		imgs["authfly"], envBlock(c.initEnv("http://stalwart:8080", sd), "      "), sec("stalwart_admin", "service_password"),
		imgs["authfly"], envBlock(ae, "      "), sec("stalwart_service", "authfly_secret", "admin_key"), httpPorts, hardening,
		imgs["console"], envBlock(c.consoleEnv("http://stalwart:8080", "http://authfly:4001", sd, "/data"), "      "), sec("stalwart_admin", "admin_key", "console_admin", "console_secret"), c.Ports.Console, hardening)
	for _, n := range []string{"stalwart_admin", "stalwart_service", "service_password", "authfly_secret", "admin_key", "console_admin", "console_secret"} {
		fmt.Fprintf(&b, "  %s: { file: run/%s }\n", n, n)
	}
	if err := writeFile(filepath.Join(c.State(), "stalwart", "config.json"), `{"@type":"RocksDb","path":"/var/lib/stalwart/"}`+"\n"); err != nil {
		return err
	}
	return writeFile(d.composeFile(), b.String())
}

// prepare writes secrets, credential files (owned by the container uid 10001, mode 0600), documents and compose.
func (d Docker) prepare(rel *Release, p Pack) error {
	c := d.C
	if _, err := c.EnsureSecrets(); err != nil {
		return err
	}
	if err := c.writeCredentialFiles(); err != nil {
		return err
	}
	for _, n := range []string{"stalwart_admin", "stalwart_service", "service_password", "authfly_secret", "admin_key", "console_admin", "console_secret"} {
		os.Chown(filepath.Join(c.State(), "run", n), 10001, 10001) // compose file secrets keep host ownership
	}
	os.Chmod(filepath.Join(c.State(), "run"), 0o711)
	if err := os.MkdirAll(filepath.Join(c.State(), "legal"), 0o755); err != nil {
		return err
	}
	if err := c.WriteDocuments(p); err != nil {
		return err
	}
	return d.Render(rel, p)
}

func (d Docker) Deploy(rel *Release, p Pack) error {
	if err := d.prepare(rel, p); err != nil {
		return err
	}
	Log("compose up (project %s)", d.project())
	if out, err := d.compose("up", "-d", "--remove-orphans", "--wait", "--wait-timeout", "180", "stalwart", "authfly", "console"); err != nil {
		return fmt.Errorf("%w\n%s", err, out)
	}
	return d.health()
}

func (d Docker) health() error {
	scheme := "http"
	if d.C.HTTP.TLS != "off" {
		scheme = "https"
	}
	return waitHTTP(fmt.Sprintf("%s://127.0.0.1:%d/api/v1/config", scheme, d.C.HTTP.Port), 90*time.Second)
}

func (d Docker) Status() (string, error) {
	return d.compose("ps", "--format", "table {{.Service}}\t{{.State}}\t{{.Ports}}")
}

func (d Docker) volumes() map[string]string { // backup name -> docker volume
	p := d.project()
	return map[string]string{"stalwart": p + "_stalwart-data", "authfly": p + "_authfly-data", "console": p + "_console-data"}
}

func (d Docker) Stop() error { _, err := d.compose("stop"); return err }
func (d Docker) Start() error {
	_, err := d.compose("up", "-d", "stalwart", "authfly", "console")
	return err
}

// Down removes the containers and network (volumes stay unless purge).
func (d Docker) Down(purge bool) error {
	args := []string{"down", "--remove-orphans"}
	if purge {
		args = append(args, "-v")
	}
	_, err := d.compose(args...)
	return err
}
