// Pack is what a policy pack sets. Every legal statement has a primary-source citation in docs/policies.md; items we
// could not verify are marked "UNVERIFIED" there and in the generated templates.
type Pack struct {
	ID             string
	Title          string
	AuditRetention time.Duration // AUTHFLY_AUDIT_RETENTION
	ResponseDays   string        // data-subject request deadline
	BreachNotice   string        // incident notification deadline
	LogIP          string        // IP logging policy of Authfly (audit log) and the advice for Stalwart logs
	Residency      string        // "" or ISO country the data must stay in
	TermsLabel     string        // sign-up checkbox text
	ExtraConsents  []string      // consent records besides "terms"
	Endpoints      []string      // data-subject endpoints that must be reachable
	Reminders      []string      // things the webmaster must do outside the software
	Documents      map[string]string
}

const notLegalAdvice = "> TEMPLATE, NOT LEGAL ADVICE. Generated by Authfly from authfly.yaml. Have it reviewed by a lawyer before publishing.\n\n"

var commonEndpoints = []string{
	"GET  /api/v1/me/export   (access + portability: JSON of profile, consents, audit)",
	"GET  /api/v1/me/consents (consent records)",
	"POST /api/v1/me/sign-out-everywhere",
	"DELETE /api/v1/me (self-service erasure, password re-check)",
	"Erasure by the operator: Console > Users > Erase, or the internal admin API POST /admin/v1/users/{addr}/erase (verified destroy + blob purge + pseudonymised audit)",
}

// PackFor builds the pack for a config (operator names and contacts are filled into the templates).
func PackFor(c *Config) Pack {
	op, contact := c.Policy.Operator, c.Policy.Contact
	if op == "" {
		op = "[OPERATOR LEGAL NAME]"
	}
	if contact == "" {
		contact = "privacy@" + c.Domain
	}
	switch c.Policy.Pack {
	case "gdpr":
		return Pack{ID: "gdpr", Title: "GDPR (EU) — Regulation (EU) 2016/679",
			AuditRetention: 365 * 24 * time.Hour, ResponseDays: "1 month, extendable by 2 months (Art. 12(3))", BreachNotice: "72 hours to the supervisory authority (Art. 33)",
			LogIP:      "none: the Authfly audit log stores no IP addresses (Art. 5(1)(c) data minimisation); keep Stalwart logs short (Art. 5(1)(e))",
			TermsLabel: "I accept the terms and the privacy notice (" + c.PublicURL + "/legal/privacy)", Endpoints: commonEndpoints,
			Reminders: []string{
				"Publish the privacy notice (Art. 13) and fill in every [BRACKET].",
				"Keep the records of processing activities (Art. 30): records-of-processing.md is a starting point.",
				"Sign a DPA (Art. 28) with your hosting provider and with every processor; dpa.md is a template for your own customers.",
				"If the server is outside the EU/EEA, check the transfer basis (Chapter V, Art. 44-49).",
			},
			Documents: map[string]string{"privacy": gdprPrivacy(c, op, contact), "dpa": dpa(c, op, "GDPR Art. 28(3)"), "records-of-processing": ropa(c, op)}}
	case "us-pii":
		return Pack{ID: "us-pii", Title: "US PII — CCPA as amended by CPRA (Cal. Civ. Code §1798.100 et seq.)",
			AuditRetention: 365 * 24 * time.Hour, ResponseDays: "45 days, one 45-day extension with notice (§1798.130(a)(2))",
			BreachNotice: "California: notice to residents 'in the most expedient time possible' (Civ. Code §1798.82); other states: own statutes (UNVERIFIED per state)",
			LogIP:        "none in the Authfly audit log; IP addresses are personal information under §1798.140(v)(1)(A) if you keep them elsewhere",
			TermsLabel:   "I accept the terms and the privacy policy, including the notice at collection (" + c.PublicURL + "/legal/privacy)", Endpoints: commonEndpoints,
			Reminders: []string{
				"State scope: " + strings.Join(c.Policy.USStates, ", ") + ". Only California (CCPA/CPRA) is verified in docs/policies.md; other state laws are listed as UNVERIFIED.",
				"Check the applicability thresholds of §1798.140(d) (annual revenue threshold is CPI-adjusted: UNVERIFIED current amount).",
				"Disclose the retention period per category (§1798.100(a)(3)) — filled in privacy.md.",
				"Authfly does not sell or share personal information; if your app does, add the 'Do Not Sell or Share' link (§1798.135).",
			},
			Documents: map[string]string{"privacy": usPrivacy(c, op, contact), "dpa": dpa(c, op, "CCPA service-provider contract (§1798.100(d), §1798.140(ag))")}}
	case "ru-152fz":
		return Pack{ID: "ru-152fz", Title: "RU 152-FZ «О персональных данных»",
			AuditRetention: 365 * 24 * time.Hour, ResponseDays: "10 working days, +5 with a reasoned notice (Art. 20 parts 1, 3 as amended)",
			BreachNotice: "Roskomnadzor within 24 hours (initial) and 72 hours (investigation results) (Art. 21 part 3.1)",
			LogIP:        "none in the Authfly audit log (data minimisation, Art. 5 part 7)",
			Residency:    "RU", TermsLabel: "Я принимаю условия и даю отдельное согласие на обработку персональных данных (" + c.PublicURL + "/legal/pd-consent)",
			ExtraConsents: []string{"pd_processing"}, Endpoints: commonEndpoints,
			Reminders: []string{
				"Notify Roskomnadzor BEFORE processing starts (Art. 22) — pd.rkn.gov.ru. Authfly cannot do this for you.",
				"Data localisation (Art. 18 part 5, in force since 2025-07-01 in the 23-FZ wording): the server and every database with RF citizens' data must be in Russia. Set policy.host_country: RU and keep backups in Russia.",
				"The consent to processing is a separate document (Art. 9 part 1, from 2025-09-01): pd-consent.md is served at /legal/pd-consent and recorded as consent kind pd_processing.",
				"Cross-border transfer needs a prior notice to Roskomnadzor (Art. 12 part 3).",
				"Publish the processing policy (Art. 18.1 part 2): privacy.md.",
			},
			Documents: map[string]string{"privacy": ruPolicy(c, op, contact), "pd-consent": ruConsent(c, op), "dpa": dpa(c, op, "поручение оператора, ст. 6 ч. 3 152-ФЗ")}}
	}
	return Pack{ID: "none", Title: "No policy pack", AuditRetention: 365 * 24 * time.Hour, LogIP: "none in the Authfly audit log", Endpoints: commonEndpoints}
}

// WriteDocuments renders the pack's templates into .authfly/legal (served at /legal/{name}).
func (c *Config) WriteDocuments(p Pack) error {
	for n, d := range p.Documents {
		if err := writeFile(filepath.Join(c.State(), "legal", n+".md"), d); err != nil {
			return err
		}
	}
	return nil
}

func retentionTable(c *Config) string {
	return "| Category | Purpose | Retention |\n|---|---|---|\n" +
		"| Account (name, email address, password hash in Stalwart) | sign-in, the service you signed up for | until you delete the account or ask for erasure |\n" +
		"| Consent records (kind, version, time) | proof of consent | as long as the account exists, then pseudonymised |\n" +
		"| Security audit log (event, time, pseudonymised subject; no IP addresses) | security, accountability | " + fmt.Sprint(PackFor0(c).AuditRetention.Hours()/24) + " days |\n" +
		"| Mailbox content (Stalwart) | email delivery of sign-in links and notices | until deleted or the account is erased |\n"
}

// PackFor0 avoids recursion when a template needs the retention (templates are built inside PackFor).
func PackFor0(c *Config) Pack { return Pack{AuditRetention: 365 * 24 * time.Hour} }

func gdprPrivacy(c *Config, op, contact string) string {
	return notLegalAdvice + "# Privacy notice\n\nController: " + op + ", contact " + contact + " (Art. 13(1)(a)).\n\n" +
		"## What we process and why\n\nWe process your account data to let you sign in (Art. 6(1)(b), contract) and keep a security log (Art. 6(1)(f), legitimate interest in securing the service).\n\n" +
		retentionTable(c) + "\n## Your rights\n\nAccess and portability (Art. 15, 20): download everything at " + c.PublicURL + "/account (export) or GET /api/v1/me/export. " +
		"Rectification (Art. 16), erasure (Art. 17), restriction (Art. 18), objection (Art. 21): write to " + contact + ". We answer within one month (Art. 12(3)). " +
		"You may withdraw consent at any time (Art. 7(3)) and lodge a complaint with a supervisory authority (Art. 77).\n\n" +
		"## Where the data is\n\nServers: [COUNTRY / PROVIDER]. Transfers outside the EU/EEA: [NONE / basis under Art. 46].\n"
}

func usPrivacy(c *Config, op, contact string) string {
	return notLegalAdvice + "# Privacy policy and notice at collection\n\nBusiness: " + op + ", contact " + contact + ".\n\n" +
		"## Categories, purposes and retention (Cal. Civ. Code §1798.100(a))\n\n" + retentionTable(c) +
		"\nWe do not sell or share personal information (§1798.120). We do not use sensitive personal information beyond what §1798.121 permits.\n\n" +
		"## Your rights (California residents)\n\nKnow/access (§1798.110), delete (§1798.105), correct (§1798.106), opt out of sale/sharing (§1798.120), limit use of sensitive PI (§1798.121), non-discrimination (§1798.125).\n" +
		"Submit a request at " + contact + " or download your data at " + c.PublicURL + "/account. We respond within 45 days (§1798.130(a)(2)).\n\n" +
		"States in scope: " + strings.Join(c.Policy.USStates, ", ") + " (only California is verified; others: UNVERIFIED, review with counsel).\n"
}

