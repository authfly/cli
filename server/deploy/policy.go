func dpa(c *Config, op, basis string) string {
	return notLegalAdvice + "# Data processing agreement (template)\n\nBasis: " + basis + ".\n\nProcessor/service provider: " + op + ". Service: authentication at " + c.PublicURL + ".\n\n" +
		"1. Subject matter and duration: account and sign-in data for the term of the main agreement.\n2. Processing only on documented instructions.\n3. Confidentiality of personnel.\n" +
		"4. Security measures: see docs/security.md (TLS, secrets 0600, localhost-only management, least-privilege service account, encrypted backups, hash-chained audit log).\n" +
		"5. Sub-processors: [HOSTING PROVIDER].\n6. Assistance with data-subject requests: export and erasure endpoints.\n7. Deletion or return at the end.\n8. Audits: `authfly doctor` report on request.\n"
}

func ropa(c *Config, op string) string {
	return notLegalAdvice + "# Records of processing activities (Art. 30)\n\n| Field | Value |\n|---|---|\n| Controller | " + op + " |\n| Purpose | authentication for " + c.PublicURL + " |\n" +
		"| Data subjects | users |\n| Categories | name, email, password hash, consent records, security events |\n| Recipients | none (self-hosted) |\n| Transfers | [NONE] |\n" +
		"| Retention | see privacy.md |\n| Security (Art. 32) | docs/security.md |\n"
}
